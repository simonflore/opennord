/**
 * gen-factory-sounds — the factory pianos and samples a Stage 4 program can name, with
 * the id a program stores for each (clavia/sound-id.ts). Built from the committed
 * factory catalog (src/lib/device/factory-libs.generated.ts, itself generated from
 * Nord's public manifest by gen-factory-libs.mjs); no network.
 *
 * Kept: every piano, and the samples in the formats a Stage 4 plays (.nsmp3, .nsmp4).
 * Each piano carries its catalog group (the first number of its category, the same
 * piano type a .npno file stores — the maintainers’ notes).
 *
 * Run from packages/core after regenerating the catalog:
 *   npm run gen:factory-sounds
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { FACTORY_LIBS } from '@/lib/device/factory-libs.generated';
import { libraryName, soundId } from '@/lib/clavia/sound-id';

const OUT = resolve('src/lib/ns4/factory-sounds.generated.ts'); // run from packages/core

const seen = new Set<string>();
const rows: string[] = [];
for (const e of FACTORY_LIBS) {
  const ext = e.filename.slice(e.filename.lastIndexOf('.') + 1);
  if (e.type === 'sample' && ext !== 'nsmp3' && ext !== 'nsmp4') continue;
  const library = libraryName(e.filename, e.type);
  if (seen.has(library)) continue;
  seen.add(library);
  const group = e.type === 'piano' ? Number(e.category.split(',')[0]) : undefined;
  rows.push(JSON.stringify({
    id: soundId(library), kind: e.type, library, version: e.version,
    ...(e.sizeDescription ? { size: e.sizeDescription } : {}),
    ...(group !== undefined && Number.isFinite(group) ? { group } : {}),
  }));
}

writeFileSync(OUT, `// AUTO-GENERATED by scripts/gen-factory-sounds.ts from src/lib/device/factory-libs.generated.ts — DO NOT EDIT.
// The factory pianos and samples a Stage 4 program can name, with the id a program stores (clavia/sound-id.ts).

export interface FactorySound {
  /** The id a program stores for this sound. */
  id: number;
  kind: 'piano' | 'sample';
  /** The library name the id is the hash of, e.g. "White Grand XL 6.3". */
  library: string;
  version: string;
  /** A piano's size (XL, L, M, S); samples have none. */
  size?: string;
  /** A piano's catalog group: the piano type a .npno file stores. */
  group?: number;
}

export const FACTORY_SOUNDS: readonly FactorySound[] = [
${rows.map((r) => `  ${r},`).join('\n')}
];
`);
console.log(`${rows.length} sounds → ${OUT}`);
