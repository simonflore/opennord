/**
 * Reader for **legacy (formatType 0) CBIN records** — the Lead 4 (`.nl4s` /
 * `.nl4p`), Lead A1 (`.nlas` / `.nlap`), Electro 3 / 3 HP (`.nepg`), Electro 4
 * (`.ne4p`), C2D (`.nc2p`), Wave (`.nwp`) and Stage 2 / 2 EX (`.ns2p`) program
 * files.
 *
 * These are not registry block chains (block-chain.ts). The firmware writes a
 * record version and then the record data, one MSB-first bitstream of
 * descriptor-table parameters stored raw (descriptor minimum 0); the Lead A1's
 * and the Wave's inline morph deltas are two's complement (medium). One rule
 * places the record for every model: it starts at **file 0x18** after a legacy
 * header (at 0x2C after an NSM-era header), so the data follows a u16 version
 * at **file 0x1A** (Electro 3/4, C2D, the Leads) or a u8 version at **file
 * 0x19** (Wave). A legacy file closes with a 2-byte trailer (the LE CRC-16 of
 * crc16.ts on the Lead and Wave files; unverified on the Electro and C2D); an
 * NSM-era file has none (the Stage 2's 565-byte `.ns2p`: data from 0x2E to the
 * end, checked on real files). NSM also copies the version to the CBIN version
 * field at 0x14. Some layouts pad
 * the record after the data (`padBytes`: the Wave's 2).
 *
 * Sources: Lead 4 OS 1.32 serialiser FUN_c01208a8 → FUN_c01156b4 and record
 * sizes FUN_c00fa160 (26 + 315 + 2 = 343 = `.nl4s`); Lead A1 OS 1.36
 * FUN_c012414c (26 + 95 + 2 = 123 = `.nlas`); Electro 4 OS 1.22 serialiser
 * FUN_3000C93A (26 + 108 + 2 = 136 = `.ne4p`); Electro 3 OS 3.14 / 3 HP OS 3.16
 * (26 + 108 + 2 = 136); C2D OS 1.12 (26 + 345 + 2 = 373); Wave OS 2.14 write
 * FUN_300056A4 / read FUN_30005906 (24 + 1 + 321 + 2 pad + 2 = 350 = `.nwp`);
 * Stage 2 OS 3.00 FUN_30032F1A / FUN_30032CCE (26 + 519 + 2 = 547, or
 * 46 + 519 = 565 behind the NSM-era header).
 * Per-model layouts are generated by `scripts/gen-fw-program-maps.py`
 * (`<model>/layout.generated.ts`). Pure; model → clavia.
 */
import { readBits } from './bitstream';
import { fieldValue, type FwEncoding } from './block-chain';

/** File offset where legacy formatType-0 record data begins (after a u16 record version). */
export const LEGACY_DATA_OFFSET = 0x1a;

/** File offset of the record (its version first) after a legacy formatType-0 header. */
export const LEGACY_RECORD_OFFSET = 0x18;

/** File offset of the record after an NSM-era (formatType 1) 44-byte header. */
export const NSM_RECORD_OFFSET = 0x2c;

/** One descriptor parameter. `bit` is relative to the start of its record. */
export interface LegacyField<K extends string = string> {
  readonly key: K;
  /** The descriptor's label (a manual name where the CC matched, else "param N"). */
  readonly name: string;
  /** Descriptor index within its parameter set (what the Lead 4 morph lists refer to). */
  readonly id: number;
  readonly bit: number;
  readonly width: number;
  readonly min: number;
  readonly max: number;
  readonly def: number;
  readonly enc: FwEncoding;
  readonly confidence: 'high' | 'medium';
  /** Firmware citation. */
  readonly src: string;
  /** The descriptor's control id (a MIDI CC on the Lead models). */
  readonly cc?: number;
  /** For an inline morph delta (Lead A1, Wave): the key of the parameter it modulates. */
  readonly deltaOf?: K;
  /**
   * A second stored copy of a parameter (the C2D's firmware list repeats some
   * containers): the key of the first copy. The firmware reader overwrites the
   * first copy with this one, and so does {@link readLegacyRecord}.
   */
  readonly copyOf?: K;
}

/** A Lead 4 sparse morph list: a count, then fixed {parameter index, source, signed delta} entries. */
export interface LegacyMorphList {
  /** Which parameter set the entries index (the key prefix, e.g. `slot` or `fx`). */
  readonly set: string;
  readonly countBit: number;
  readonly countWidth: number;
  readonly maxEntries: number;
  readonly entryBit: number;
  readonly paramBits: number;
  readonly sourceBits: number;
  readonly deltaBits: number;
}

export interface LegacyLayout<K extends string = string> {
  readonly model: string;
  /** Firmware descriptor tables the layout comes from. */
  readonly source: string;
  /** Firmware serialiser / record-size functions. */
  readonly container: string;
  /** The record version the firmware writes, or null when not recovered. */
  readonly recordVersion: number | null;
  /** Width of the record version in bytes: 2 (u16, the default) or 1 (the Wave's u8). */
  readonly versionBytes?: 1 | 2;
  /** Bytes of record data. */
  readonly dataBytes: number;
  /** Bytes the firmware pads the record with after the data (default 0). */
  readonly padBytes?: number;
  readonly fields: readonly LegacyField<K>[];
  readonly morphLists?: readonly LegacyMorphList[];
  /**
   * Parameter sets stored more than once (key prefix → the shared set), so a
   * parameter is counted once however many presets, manuals or slots repeat it.
   * Prefixes not listed name their own set.
   */
  readonly sets?: Readonly<Record<string, string>>;
}

/** One used morph-list entry. */
export interface LegacyMorphEntry {
  /** Descriptor index within the list's parameter set. */
  readonly param: number;
  /** Morph source index. */
  readonly source: number;
  /** Signed delta. */
  readonly delta: number;
}

/**
 * The record data of a legacy file: `dataOffset` (default file 0x1A) up to the
 * `trailerBytes`-byte trailer (default 2). For a file of either header, pass
 * {@link legacyDataOffset} and {@link legacyTrailerBytes}, or use
 * {@link legacyLayoutData}.
 */
export function legacyData(bytes: Uint8Array, dataOffset: number = LEGACY_DATA_OFFSET, trailerBytes = 2): Uint8Array {
  return bytes.slice(dataOffset, Math.max(dataOffset, bytes.length - trailerBytes));
}

/** The u16 LE record version at file 0x14. */
export function legacyRecordVersion(bytes: Uint8Array): number {
  return (bytes[0x14] ?? 0) | ((bytes[0x15] ?? 0) << 8);
}

/** Where the record (its version first) starts: 0x18 after a legacy header, 0x2C after an NSM-era header. */
export function legacyRecordOffset(bytes: Uint8Array): number {
  return bytes[0x04] === 1 ? NSM_RECORD_OFFSET : LEGACY_RECORD_OFFSET;
}

/** Where `layout`'s record data starts in this file: the record offset plus the version width. */
export function legacyDataOffset(bytes: Uint8Array, layout: Pick<LegacyLayout, 'versionBytes'>): number {
  return legacyRecordOffset(bytes) + (layout.versionBytes ?? 2);
}

/** Bytes after the record: the 2-byte CRC trailer of a legacy file (an NSM-era header carries its own checksum). */
export function legacyTrailerBytes(bytes: Uint8Array): number {
  return bytes[0x04] === 1 ? 0 : 2;
}

/** The file size the firmware record makes for this file's header. */
export function legacyFileBytes(bytes: Uint8Array, layout: LegacyLayout): number {
  return legacyDataOffset(bytes, layout) + layout.dataBytes + (layout.padBytes ?? 0) + legacyTrailerBytes(bytes);
}

/** The record data of `layout` in this file: from the data offset up to the trailer (padding included). */
export function legacyLayoutData(bytes: Uint8Array, layout: LegacyLayout): Uint8Array {
  return legacyData(bytes, legacyDataOffset(bytes, layout), legacyTrailerBytes(bytes));
}

/** The record version stored in front of the data (big-endian, `layout.versionBytes` wide). */
export function legacyLayoutVersion(bytes: Uint8Array, layout: LegacyLayout): number {
  const at = legacyRecordOffset(bytes);
  return (layout.versionBytes ?? 2) === 1 ? bytes[at] ?? 0 : ((bytes[at] ?? 0) << 8) | (bytes[at + 1] ?? 0);
}

export interface LegacyRecordRead<K extends string> {
  /** Decoded values by key. */
  values: Partial<Record<K, number>>;
  /** Keys whose value falls outside the descriptor range (the firmware resets these to default on load). */
  outOfRange: K[];
}

/**
 * Read every field of `layout` from the record starting at data byte `byteOffset`.
 * A second stored copy (`copyOf`) overwrites its first copy, as the firmware
 * reader does; both keys then hold the value the instrument uses. Never throws.
 */
export function readLegacyRecord<K extends string>(
  data: Uint8Array, layout: LegacyLayout<K>, byteOffset = 0,
): LegacyRecordRead<K> {
  const values: Partial<Record<K, number>> = {};
  const outOfRange: K[] = [];
  for (const f of layout.fields) {
    const v = fieldValue(readBits(data, byteOffset * 8 + f.bit, f.width), f);
    if (v < f.min || v > f.max) outOfRange.push(f.key);
    values[f.key] = v;
  }
  for (const f of layout.fields) if (f.copyOf) values[f.copyOf] = values[f.key];
  return { values, outOfRange };
}

/** One legacy program file read against a layout (see {@link readLegacyFile}). */
export interface LegacyFileRead<K extends string> extends LegacyRecordRead<K> {
  /** The record version stored in front of the data. */
  recordVersion: number;
  /** Record data: from the data offset up to the trailer (padding included). */
  data: Uint8Array;
  /** True when the file holds the whole record, so every field was read from it. */
  complete: boolean;
  warnings: string[];
}

/**
 * Read a whole legacy program file against `layout`: record version, data and
 * every field, with a warning for a short or odd-sized file, a record version
 * outside `versions`, and values outside their descriptor range. Never throws.
 */
export function readLegacyFile<K extends string>(
  bytes: Uint8Array, layout: LegacyLayout<K>, versions: readonly number[] = layout.recordVersion === null ? [] : [layout.recordVersion],
): LegacyFileRead<K> {
  const warnings: string[] = [];
  const expected = legacyFileBytes(bytes, layout);
  const data = legacyLayoutData(bytes, layout);
  const complete = data.length >= layout.dataBytes;
  if (!complete) {
    warnings.push(`File too short: ${bytes.length} bytes, the firmware record makes ${expected}`);
  } else if (bytes.length !== expected) {
    warnings.push(`Program file is ${bytes.length} bytes, the firmware record makes ${expected}`);
  }
  const recordVersion = legacyLayoutVersion(bytes, layout);
  if (versions.length > 0 && !versions.includes(recordVersion)) {
    warnings.push(`Record version ${recordVersion}; the firmware reads ${versions.join(', ')}`);
  }
  const { values, outOfRange } = readLegacyRecord(data, layout);
  if (complete && outOfRange.length > 0) {
    warnings.push(`${outOfRange.length} value(s) outside the firmware's range (${outOfRange.slice(0, 4).join(', ')}${outOfRange.length > 4 ? ', …' : ''}).`);
  }
  return { recordVersion, data, complete, values, outOfRange, warnings };
}

/** Inline morph deltas grouped under the parameter they modulate, in stored (source) order. */
export function legacyMorphDeltas<K extends string>(
  layout: LegacyLayout<K>, values: Partial<Record<K, number>>,
): Partial<Record<K, number[]>> {
  const out: Partial<Record<K, number[]>> = {};
  for (const f of layout.fields) if (f.deltaOf) (out[f.deltaOf] ??= []).push(values[f.key] ?? 0);
  return out;
}

/** The used entries of a sparse morph list (unused entries are zero and ignored). */
export function readMorphList(data: Uint8Array, list: LegacyMorphList, byteOffset = 0): LegacyMorphEntry[] {
  const base = byteOffset * 8;
  const count = Math.min(readBits(data, base + list.countBit, list.countWidth), list.maxEntries);
  const size = list.paramBits + list.sourceBits + list.deltaBits;
  const out: LegacyMorphEntry[] = [];
  for (let i = 0; i < count; i++) {
    const at = base + list.entryBit + i * size;
    out.push({
      param: readBits(data, at, list.paramBits),
      source: readBits(data, at + list.paramBits, list.sourceBits),
      delta: fieldValue(readBits(data, at + list.paramBits + list.sourceBits, list.deltaBits),
        { enc: 'twos', width: list.deltaBits, min: 0 }),
    });
  }
  return out;
}
